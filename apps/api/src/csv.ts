/**
 * Minimal RFC 4180 CSV parser: quoted fields (with embedded commas, newlines,
 * and "" escapes), CRLF or LF line endings, and a leading UTF-8 BOM.
 * Returns rows as arrays of raw cell strings; blank lines are dropped.
 */
export function parseCsv(text: string): string[][] {
  const src = text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;

  const endRow = () => {
    row.push(field);
    field = "";
    if (row.length > 1 || row[0] !== "") rows.push(row);
    row = [];
  };

  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (inQuotes) {
      if (c === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"' && field === "") {
      inQuotes = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && src[i + 1] === "\n") i++;
      endRow();
    } else {
      field += c;
    }
  }
  if (inQuotes) throw new Error("unterminated quoted field");
  if (field !== "" || row.length > 0) endRow();
  return rows;
}

/** Parse CSV with a header row into objects keyed by trimmed header names. */
export function parseCsvRecords(text: string): Record<string, string>[] {
  const [header, ...body] = parseCsv(text);
  if (!header) return [];
  const keys = header.map((h) => h.trim());
  return body.map((cols) =>
    Object.fromEntries(keys.map((k, i) => [k, (cols[i] ?? "").trim()])),
  );
}
